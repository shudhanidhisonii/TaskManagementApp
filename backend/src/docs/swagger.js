const taskExample = {
  id: '3f6c0f6e-8d1a-4c52-9f0e-7a1b2c3d4e5f',
  title: 'Build API',
  description: 'Express backend',
  status: 'in_progress',
  priority: 'high',
  dueDate: '2026-12-31T00:00:00.000Z',
  createdAt: '2026-10-24T10:15:30.000Z',
  updatedAt: '2026-10-24T10:15:30.000Z',
};

const errorBody = (message, errors) => ({
  success: false,
  message,
  ...(errors ? { errors } : {}),
});

const jsonContent = (schemaRef, examples) => ({
  'application/json': { schema: { $ref: schemaRef }, examples },
});

const swaggerSpec = {
  openapi: '3.0.3',
  info: {
    title: 'Task Management API',
    version: '1.0.0',
    description: [
      'REST API for the Task Management System (Node.js + Express).',
      '',
      '**Storage:** tasks are kept in server memory, so all data is lost when the server restarts.',
      '',
      '**Authentication:** none.',
      '',
      '**Response format:** every response has a "success" flag. Successful responses return the task(s) in "data". ' +
        'Errors return a "message" and, for validation problems, an "errors" list.',
    ].join('\n'),
  },
  servers: [{ url: '/', description: 'This server' }],
  tags: [{ name: 'Tasks', description: 'Create, read, update, delete and search tasks' }],

  paths: {
    '/api/tasks': {
      get: {
        tags: ['Tasks'],
        operationId: 'getAllTasks',
        summary: 'Get all tasks',
        description:
          'Returns every task. Add the optional "search" query parameter to return only tasks whose ' +
          'title or description contains the text (case-insensitive). An empty or whitespace-only ' +
          'search returns all tasks.',
        parameters: [
          {
            name: 'search',
            in: 'query',
            required: false,
            description: 'Text to look for in the task title or description (case-insensitive).',
            schema: { type: 'string' },
            example: 'pricing',
          },
        ],
        responses: {
          200: {
            description: 'List of tasks (empty list when nothing matches).',
            content: jsonContent('#/components/schemas/TaskListResponse', {
              allTasks: { summary: 'All tasks', value: { success: true, count: 1, data: [taskExample] } },
              noMatch: { summary: 'No match for the search', value: { success: true, count: 0, data: [] } },
            }),
          },
          400: {
            description: 'The "search" parameter was sent more than once.',
            content: jsonContent('#/components/schemas/ErrorResponse', {
              invalidSearch: {
                value: errorBody('Query parameter "search" must be a single text value'),
              },
            }),
          },
          500: { $ref: '#/components/responses/ServerError' },
        },
      },

      post: {
        tags: ['Tasks'],
        operationId: 'createTask',
        summary: 'Create a task',
        description:
          'Only "title" is required. Defaults: status "pending", priority "medium", description "", dueDate null. ' +
          'The id, createdAt and updatedAt values are generated by the server.',
        requestBody: {
          required: true,
          content: {
            'application/json': {
              schema: { $ref: '#/components/schemas/TaskCreate' },
              examples: {
                minimal: { summary: 'Only the required field', value: { title: 'Write documentation' } },
                full: {
                  summary: 'All fields',
                  value: {
                    title: 'Build API',
                    description: 'Express backend',
                    status: 'in_progress',
                    priority: 'high',
                    dueDate: '2026-12-31',
                  },
                },
              },
            },
          },
        },
        responses: {
          201: {
            description: 'Task created.',
            content: jsonContent('#/components/schemas/TaskMutationResponse', {
              created: {
                value: { success: true, message: 'Task created successfully', data: taskExample },
              },
            }),
          },
          400: {
            description: 'Validation failed, the body is not a JSON object, or the JSON is invalid.',
            content: jsonContent('#/components/schemas/ErrorResponse', {
              validation: {
                summary: 'Validation failed',
                value: errorBody('Validation failed', [
                  'title is required and must be a non-empty string',
                  'status must be one of: pending, in_progress, completed',
                ]),
              },
              invalidJson: { summary: 'Malformed JSON', value: errorBody('Invalid JSON in request body') },
              notObject: { summary: 'Body is not an object', value: errorBody('Request body must be a JSON object') },
            }),
          },
          500: { $ref: '#/components/responses/ServerError' },
        },
      },
    },

    '/api/tasks/{id}': {
      parameters: [{ $ref: '#/components/parameters/TaskId' }],

      get: {
        tags: ['Tasks'],
        operationId: 'getTaskById',
        summary: 'Get one task',
        responses: {
          200: {
            description: 'The task.',
            content: jsonContent('#/components/schemas/TaskResponse', {
              found: { value: { success: true, data: taskExample } },
            }),
          },
          404: { $ref: '#/components/responses/NotFound' },
          500: { $ref: '#/components/responses/ServerError' },
        },
      },

      put: {
        tags: ['Tasks'],
        operationId: 'updateTask',
        summary: 'Update a task',
        description:
          'Send only the fields you want to change (at least one). The fields id, createdAt and updatedAt ' +
          'cannot be changed: they are ignored if sent. updatedAt is refreshed automatically.',
        requestBody: {
          required: true,
          content: {
            'application/json': {
              schema: { $ref: '#/components/schemas/TaskUpdate' },
              examples: {
                markCompleted: { summary: 'Change the status', value: { status: 'completed' } },
                clearDueDate: { summary: 'Remove the due date', value: { dueDate: null } },
                several: {
                  summary: 'Change several fields',
                  value: { title: 'Build REST API', priority: 'medium', dueDate: '2027-01-15' },
                },
              },
            },
          },
        },
        responses: {
          200: {
            description: 'Task updated.',
            content: jsonContent('#/components/schemas/TaskMutationResponse', {
              updated: {
                value: {
                  success: true,
                  message: 'Task updated successfully',
                  data: { ...taskExample, status: 'completed', updatedAt: '2026-10-24T11:00:00.000Z' },
                },
              },
            }),
          },
          400: {
            description: 'Validation failed, no updatable fields were sent, or the JSON is invalid.',
            content: jsonContent('#/components/schemas/ErrorResponse', {
              validation: {
                summary: 'Validation failed',
                value: errorBody('Validation failed', ['status must be one of: pending, in_progress, completed']),
              },
              nothingToUpdate: {
                summary: 'No updatable fields',
                value: errorBody('No updatable fields provided', [
                  'Send at least one of: title, description, status, priority, dueDate',
                ]),
              },
              invalidJson: { summary: 'Malformed JSON', value: errorBody('Invalid JSON in request body') },
            }),
          },
          404: { $ref: '#/components/responses/NotFound' },
          500: { $ref: '#/components/responses/ServerError' },
        },
      },

      delete: {
        tags: ['Tasks'],
        operationId: 'deleteTask',
        summary: 'Delete a task',
        description: 'Permanently removes the task and returns the task that was deleted.',
        responses: {
          200: {
            description: 'Task deleted.',
            content: jsonContent('#/components/schemas/TaskMutationResponse', {
              deleted: {
                value: { success: true, message: 'Task deleted successfully', data: taskExample },
              },
            }),
          },
          404: { $ref: '#/components/responses/NotFound' },
          500: { $ref: '#/components/responses/ServerError' },
        },
      },
    },
  },

  components: {
    parameters: {
      TaskId: {
        name: 'id',
        in: 'path',
        required: true,
        description: 'Task id (UUID returned when the task was created).',
        schema: { type: 'string' },
        example: taskExample.id,
      },
    },

    responses: {
      NotFound: {
        description: 'No task exists with this id.',
        content: jsonContent('#/components/schemas/ErrorResponse', {
          notFound: { value: errorBody('Task with id "abc123" not found') },
        }),
      },
      ServerError: {
        description: 'Unexpected server error.',
        content: jsonContent('#/components/schemas/ErrorResponse', {
          serverError: { value: errorBody('Internal server error') },
        }),
      },
    },

    schemas: {
      Task: {
        type: 'object',
        required: ['id', 'title', 'description', 'status', 'priority', 'dueDate', 'createdAt', 'updatedAt'],
        properties: {
          id: { type: 'string', format: 'uuid', description: 'Generated by the server.', example: taskExample.id },
          title: { type: 'string', example: taskExample.title },
          description: { type: 'string', example: taskExample.description },
          status: { type: 'string', enum: ['pending', 'in_progress', 'completed'], example: 'in_progress' },
          priority: { type: 'string', enum: ['low', 'medium', 'high'], example: 'high' },
          dueDate: {
            type: 'string',
            format: 'date-time',
            nullable: true,
            description: 'Due date, or null when none is set.',
            example: taskExample.dueDate,
          },
          createdAt: { type: 'string', format: 'date-time', example: taskExample.createdAt },
          updatedAt: { type: 'string', format: 'date-time', example: taskExample.updatedAt },
        },
      },

      TaskCreate: {
        type: 'object',
        required: ['title'],
        properties: {
          title: { type: 'string', minLength: 1, description: 'Required. Leading/trailing spaces are trimmed.', example: 'Build API' },
          description: { type: 'string', default: '', example: 'Express backend' },
          status: { type: 'string', enum: ['pending', 'in_progress', 'completed'], default: 'pending' },
          priority: { type: 'string', enum: ['low', 'medium', 'high'], default: 'medium' },
          dueDate: {
            type: 'string',
            nullable: true,
            description: 'Any valid date string, e.g. "2026-12-31" or "2026-12-31T10:00:00Z". Stored as an ISO date-time.',
            example: '2026-12-31',
          },
        },
      },

      TaskUpdate: {
        type: 'object',
        minProperties: 1,
        description: 'All fields are optional, but at least one must be sent. Unknown fields (including id, createdAt, updatedAt) are ignored.',
        properties: {
          title: { type: 'string', minLength: 1, example: 'Build REST API' },
          description: { type: 'string', example: 'Express backend' },
          status: { type: 'string', enum: ['pending', 'in_progress', 'completed'] },
          priority: { type: 'string', enum: ['low', 'medium', 'high'] },
          dueDate: {
            type: 'string',
            nullable: true,
            description: 'A valid date string, or null / empty string to remove the due date.',
            example: '2027-01-15',
          },
        },
      },

      TaskResponse: {
        type: 'object',
        required: ['success', 'data'],
        properties: {
          success: { type: 'boolean', example: true },
          data: { $ref: '#/components/schemas/Task' },
        },
      },

      TaskListResponse: {
        type: 'object',
        required: ['success', 'count', 'data'],
        properties: {
          success: { type: 'boolean', example: true },
          count: { type: 'integer', description: 'Number of tasks returned.', example: 1 },
          data: { type: 'array', items: { $ref: '#/components/schemas/Task' } },
        },
      },

      TaskMutationResponse: {
        type: 'object',
        required: ['success', 'message', 'data'],
        properties: {
          success: { type: 'boolean', example: true },
          message: { type: 'string', example: 'Task created successfully' },
          data: { $ref: '#/components/schemas/Task' },
        },
      },

      ErrorResponse: {
        type: 'object',
        required: ['success', 'message'],
        properties: {
          success: { type: 'boolean', example: false },
          message: { type: 'string', example: 'Validation failed' },
          errors: {
            type: 'array',
            description: 'Detailed messages (only present for some validation errors).',
            items: { type: 'string' },
            example: ['title is required and must be a non-empty string'],
          },
        },
      },
    },
  },
};

export default swaggerSpec;